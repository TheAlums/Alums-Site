#!/usr/bin/env node
/* Build step for the canonical alumni file.
   Source of truth: data/alumni.json (read by the site, the box bot and the news bot).
   Writes:
     js/alumni-canonical.js  -> FLOCK.alumniData / FLOCK.alumni / FLOCK.alumniView(view) for the browser
     worker/boxbot.js         -> the ROSTER block between the BEGIN/END ROSTER markers
   Usage: node scripts/build-alumni.mjs          (write)
          node scripts/build-alumni.mjs --check  (exit 1 if either output is stale) */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const data = JSON.parse(fs.readFileSync(path.join(root, "data/alumni.json"), "utf8"));

const js = `/* GENERATED by scripts/build-alumni.mjs from data/alumni.json (asOf ${data.asOf}). Do not edit by hand. */
(function () {
  window.FLOCK = window.FLOCK || {};
  var DATA = ${JSON.stringify(data)};
  FLOCK.alumniData = DATA;
  FLOCK.alumni = DATA.players;
  function clone(o) { return JSON.parse(JSON.stringify(o)); }
  /* Legacy shapes, in the original file order, so data.js / alumni.js / dictionary.js keep exporting
     the same FLOCK.players and FLOCK.dictionary rows the week scripts and rivalry.js read. */
  FLOCK.alumniView = function (view) {
    return DATA.players
      .filter(function (p) { return p.site && p.site.views && p.site.views[view] != null; })
      .sort(function (a, b) { return a.site.views[view] - b.site.views[view]; })
      .map(function (p) {
        if (view === "dictionary") {
          var d = p.site.dictionaryRow || {};
          return { id: p.id, name: p.name, pos: d.pos || p.pos, team: p.team, teamName: p.teamName, jersey: d.jersey !== undefined ? d.jersey : p.jersey,
            school: "oregon", league: "NFL", yearsAtOregon: d.yearsAtOregon || "", roster: d.roster, statusLabel: d.statusLabel };
        }
        var row = { id: p.id, name: p.name, pos: p.pos, team: p.team, teamName: p.teamName, league: p.league, school: p.school };
        if (p.jersey != null) row.jersey = p.jersey;
        var prof = clone(p.site.profile || {});
        Object.keys(prof).forEach(function (k) { row[k] = prof[k]; });
        return row;
      });
  };
})();
`;
const rosterRows = data.players
  .filter((p) => p.boxbotRoster)
  .sort((a, b) => a.site.views.boxbotRoster - b.site.views.boxbotRoster)
  .map((p) => `  [${JSON.stringify(p.id)}, ${JSON.stringify(p.boxbotName || p.name)}]`);
const block = `/* BEGIN ROSTER (generated from data/alumni.json by scripts/build-alumni.mjs) */\nconst ROSTER = [\n${rosterRows.join(",\n")}\n];\n/* END ROSTER */`;
const workerPath = path.join(root, "worker/boxbot.js");
const worker = fs.readFileSync(workerPath, "utf8");
const re = /\/\* BEGIN ROSTER[\s\S]*?\/\* END ROSTER \*\/|const ROSTER = \[[\s\S]*?\n\];/;
if (!re.test(worker)) throw new Error("ROSTER block not found in worker/boxbot.js");
const worker2 = worker.replace(re, block);
const jsPath = path.join(root, "js/alumni-canonical.js");
const stale = [];
if (!fs.existsSync(jsPath) || fs.readFileSync(jsPath, "utf8") !== js) stale.push("js/alumni-canonical.js");
if (worker2 !== worker) stale.push("worker/boxbot.js ROSTER");
if (check) {
  if (stale.length) { console.error("stale: " + stale.join(", ")); process.exit(1); }
  console.log("up to date:", data.players.length, "players,", rosterRows.length, "ROSTER rows");
} else {
  fs.writeFileSync(jsPath, js);
  fs.writeFileSync(workerPath, worker2);
  console.log("wrote js/alumni-canonical.js and worker ROSTER (" + rosterRows.length + " rows); players:", data.players.length);
}
